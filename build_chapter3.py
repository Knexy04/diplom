from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_LINE_SPACING
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

ROOT = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.join(ROOT, 'diagrams', 'chapter3')
RUNS = os.path.join(ROOT, 'runs/detect/runs/detect/adult_child')
MASTER = os.path.join(ROOT, 'Маркин_отчёт_по_преддипломной_часть_2_ИСПРАВЛЕННОЕ.docx')

# Режим: --append дописывает главу в конец мастер-файла, иначе — отдельный docx
APPEND = '--append' in sys.argv

if APPEND:
    # бэкап мастер-файла перед необратимой правкой
    backup = MASTER.replace('.docx', '.backup-before-ch3.docx')
    shutil.copy(MASTER, backup)
    print('backup ->', backup)
    doc = Document(MASTER)
    doc.add_page_break()  # глава начинается с новой страницы
else:
    doc = Document()
    # --- базовый стиль (только для отдельного файла; в мастере стили уже заданы) ---
    normal = doc.styles['Normal']
    normal.font.name = 'Times New Roman'
    normal.font.size = Pt(14)
    normal._element.rPr.rFonts.set(qn('w:eastAsia'), 'Times New Roman')
    pf = normal.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf.space_after = Pt(0)
    for hi in ('Heading 1', 'Heading 2', 'Heading 3'):
        st = doc.styles[hi]
        st.font.name = 'Times New Roman'
        st.font.color.rgb = RGBColor(0, 0, 0)
        st._element.rPr.rFonts.set(qn('w:eastAsia'), 'Times New Roman')
    doc.styles['Heading 1'].font.size = Pt(16)
    doc.styles['Heading 2'].font.size = Pt(15)
    doc.styles['Heading 3'].font.size = Pt(14)


def h1(t):
    p = doc.add_heading(t, level=1)
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    return p

def h2(t):
    p = doc.add_heading(t, level=2)
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    return p

def h3(t):
    p = doc.add_heading(t, level=3)
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    return p

def para(t, indent=True):
    p = doc.add_paragraph(t)
    p.paragraph_format.first_line_indent = Cm(1.25) if indent else Cm(0)
    return p

def bullet(t):
    p = doc.add_paragraph(t, style='List Paragraph')
    p.paragraph_format.first_line_indent = Cm(0)
    # маркер «–»
    p.insert_paragraph_before  # noop
    r = p.runs[0]
    p.text = '– ' + t
    for rr in p.runs:
        rr.font.name = 'Times New Roman'; rr.font.size = Pt(14)
    p.paragraph_format.left_indent = Cm(1.0)
    return p

def fig(path, caption, width=Cm(16)):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    if path and os.path.exists(path):
        p.add_run().add_picture(path, width=width)
    else:
        r = p.add_run(f'[ЗДЕСЬ БУДЕТ {caption.split(" – ")[0].upper()} — вставить изображение]')
        r.font.color.rgb = RGBColor(0x99, 0x55, 0x00); r.italic = True
        r.font.size = Pt(12)
    c = doc.add_paragraph(caption)
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraph_format.first_line_indent = Cm(0)
    c.paragraph_format.space_after = Pt(6)
    for rr in c.runs:
        rr.font.size = Pt(12)
    return p

def placeholder_fig(caption, note=''):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    txt = f'[ПЛЕЙСХОЛДЕР РИСУНКА — {note}]' if note else '[ПЛЕЙСХОЛДЕР РИСУНКА]'
    r = p.add_run(txt)
    r.font.color.rgb = RGBColor(0x99, 0x55, 0x00); r.italic = True
    r.font.size = Pt(12)
    c = doc.add_paragraph(caption)
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraph_format.first_line_indent = Cm(0)
    c.paragraph_format.space_after = Pt(6)
    for rr in c.runs:
        rr.font.size = Pt(12)

def table(caption, headers, rows, widths=None):
    c = doc.add_paragraph(caption)
    c.paragraph_format.first_line_indent = Cm(0)
    c.paragraph_format.space_before = Pt(6)
    for rr in c.runs:
        rr.font.size = Pt(12)
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, htext in enumerate(headers):
        hdr[i].text = ''
        pp = hdr[i].paragraphs[0]
        pp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = pp.add_run(htext); run.bold = True
        run.font.size = Pt(12); run.font.name = 'Times New Roman'
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(str_row(row)):
            cells[i].text = ''
            pp = cells[i].paragraphs[0]
            run = pp.add_run(val)
            run.font.size = Pt(12); run.font.name = 'Times New Roman'
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t

def str_row(row):
    return [str(x) for x in row]

def listing(code, caption):
    c = doc.add_paragraph(caption)
    c.paragraph_format.first_line_indent = Cm(0)
    c.paragraph_format.space_before = Pt(6)
    for rr in c.runs:
        rr.font.size = Pt(12)
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.left_indent = Cm(0.5)
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
    r = p.add_run(code)
    r.font.name = 'Consolas'; r.font.size = Pt(9.5)
    r._element.rPr.rFonts.set(qn('w:eastAsia'), 'Consolas')
    # светлая заливка
    shd = OxmlElement('w:shd'); shd.set(qn('w:fill'), 'F2F2F2')
    p._p.get_or_add_pPr().append(shd)
    return p

def note(t):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    r = p.add_run(t); r.italic = True; r.font.size = Pt(12)
    r.font.color.rgb = RGBColor(0x55, 0x55, 0x55)
    return p


